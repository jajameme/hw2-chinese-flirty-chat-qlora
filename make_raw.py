def parse_seeds(text, scenario):
    rows = []
    for line_number, line in enumerate(text.splitlines(), 1):
        parts = [part.strip() for part in line.split("|")]
        if len(parts) != 4 or not all(parts):
            raise ValueError(f"{scenario} line {line_number}: expected four fields")
        rows.append(parts)
    if len(rows) != 10:
        raise ValueError(f"{scenario}: expected ten seeds, found {len(rows)}")
    return rows


def main():
    out_dir = ROOT / "raw"
    out_dir.mkdir(exist_ok=True)
    total = 0
    review_rows = []
    for scenario, (openings, text) in SCENARIOS.items():
        rows = []
        for seed_number, (topic, first, followup, callback) in enumerate(parse_seeds(text, scenario), 1):
            seed_id = f"{scenario}-{seed_number:02d}"
            content_hash = hashlib.sha256(
                "\x1f".join((topic, first, followup, callback)).encode("utf-8")
            ).hexdigest()[:16]
            review_rows.append({"seed_id": seed_id, "scenario": scenario, "topic": topic,
                                "first_reply": first, "callback": callback,
                                "content_hash": content_hash, "approved": ""})
            for opening in openings:
                rows.append({
                    "seed_id": seed_id,
                    "scenario": scenario,
                    "messages": [
                        {"role": "user", "content": opening.format(topic=topic)},
                        {"role": "assistant", "content": first},
                        {"role": "user", "content": followup},
                        {"role": "assistant", "content": callback},
                    ],
                })
        path = out_dir / f"{scenario}.json"
        path.write_text(json.dumps(rows, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
        total += len(rows)
    review_path = ROOT / "data" / "review.csv"
    review_path.parent.mkdir(exist_ok=True)
    # Preserve existing human decisions when raw candidates are regenerated.
    if review_path.exists():
        with review_path.open(encoding="utf-8-sig", newline="") as file:
            old = {row["seed_id"]: row for row in csv.DictReader(file)}
        for row in review_rows:
            previous = old.get(row["seed_id"], {})
            if previous.get("content_hash") == row["content_hash"]:
                row["approved"] = previous.get("approved", "")
    with review_path.open("w", encoding="utf-8-sig", newline="") as file:
        writer = csv.DictWriter(file, fieldnames=list(review_rows[0]))
        writer.writeheader()
        writer.writerows(review_rows)
    print(f"Created {total} candidate conversations in {len(SCENARIOS)} scenarios")
    print(f"Review sheet: {review_path} ({len(review_rows)} gag groups; blank means pending)")


if __name__ == "__main__":
    main()
